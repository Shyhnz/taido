#!/usr/bin/env python3
"""Writes the colour theme blocks of src/styles/tokens.css (Réglages › Thème).

Each theme is a hue, a saturation and an accent lightness; every token is derived from them,
so a theme is tuned here and the blocks are regenerated:

    python3 tools/color-themes.py && pnpm vitest run src/styles/tokens.test.ts

Everything after MARKER in tokens.css is replaced. « Taido » (the default) has no block.
"""

import colorsys
from pathlib import Path

TOKENS = Path(__file__).resolve().parent.parent / "src/styles/tokens.css"
MARKER = "/* Generated by tools/color-themes.py: do not edit below. */\n"

# id (ColorTheme), hue, saturation (0-100), accent lightness in light mode. Bright hues
# (green, cyan) get a lower lightness so that white text stays readable on the accent.
THEMES = [
    ("slate", 214, 34, 40),
    ("graphite", 40, 6, 28),
    ("blueberry", 246, 58, 50),
    ("lavender", 262, 52, 52),
    ("plum", 295, 48, 40),
    ("raspberry", 330, 62, 42),
    ("cocoa", 24, 44, 36),
    ("sage", 150, 34, 32),
    ("lagoon", 184, 72, 28),
]


def hx(h: float, s: float, l: float) -> str:
    s = max(0.0, min(100.0, s))
    r, g, b = colorsys.hls_to_rgb(h / 360, l / 100, s / 100)
    return "#%02x%02x%02x" % tuple(round(c * 255) for c in (r, g, b))


def light(h: float, s: float, l: float) -> dict[str, str]:
    return {
        "bg": hx(h, 0.35 * s, 99),
        "bg-elevated": hx(h, 0.35 * s, 99),
        "bg-aside": hx(h, 0.5 * s, 96.5),
        "bg-hover": hx(h, 0.45 * s, 96.8),
        "bg-sidebar": hx(h, 0.75 * s, 92),
        "bg-sidebar-hover": hx(h, 0.75 * s, 88.5),
        "bg-nav-active": hx(h, 0.9 * s, 86),
        "text-nav-active": hx(h, s, l - 20),
        "bg-selected": hx(h, 0.85 * s, 95.3),
        "accent": hx(h, s, l),
        "focus": hx(h, s, l),
        "border": hx(h, 0.35 * s, 87),
        "border-row": hx(h, 0.3 * s, 90),
        "border-terminal": hx(h, 0.3 * s, 88),
        "text": hx(h, 0.2 * s, 13),
        "text-2": hx(h, 0.12 * s, 33),
        "text-3": hx(h, 0.14 * s, 35),
        "token-agent-bg": hx(h, 0.9 * s, 86),
        "token-agent-text": hx(h, s, l - 20),
        # A shade darker than the default: 4.5:1 on the tinted selection.
        "due-overdue": "#a64b14",
    }


def dark(h: float, s0: float, l: float) -> dict[str, str]:
    accent = hx(h, 0.9 * s0 + 8, 70)
    s = min(s0, 55)  # very saturated hues make the surfaces too loud in the dark
    return {
        "bg": hx(h, 0.35 * s, 11),
        "bg-elevated": hx(h, 0.35 * s, 15),
        "bg-aside": hx(h, 0.35 * s, 13),
        "bg-hover": hx(h, 0.35 * s, 14.5),
        "bg-sidebar": hx(h, 0.45 * s, 15.5),
        "bg-sidebar-hover": hx(h, 0.45 * s, 19.5),
        "bg-nav-active": hx(h, 0.6 * s, 25),
        "text-nav-active": hx(h, 1.1 * s, 86),
        "bg-selected": hx(h, 0.5 * s, 17.5),
        "accent": accent,
        "focus": accent,
        "on-accent": hx(h, 0.5 * s, 10),
        "border": hx(h, 0.3 * s, 24),
        "border-row": hx(h, 0.3 * s, 19),
        "border-terminal": hx(h, 0.3 * s, 26),
        "text": hx(h, 0.2 * s, 92),
        "text-2": hx(h, 0.15 * s, 73),
        "text-3": hx(h, 0.15 * s, 66),
        "ring-check-on-fill": hx(h, 0.35 * s, 11),
        "token-agent-bg": hx(h, 0.6 * s, 25),
        "token-agent-text": hx(h, 1.1 * s, 86),
    }


def blocks() -> str:
    out = []
    for theme_id, h, s, l in THEMES:
        for mode, tokens in (("light", light), ("dark", dark)):
            body = "".join(f"  --{k}: {v};\n" for k, v in tokens(h, s, l).items())
            out.append(f'[data-theme="{mode}"][data-color="{theme_id}"] {{\n{body}}}\n')
    return "\n".join(out)


def main() -> None:
    css = TOKENS.read_text(encoding="utf-8")
    at = css.index(MARKER) + len(MARKER)
    TOKENS.write_text(css[:at] + "\n" + blocks(), encoding="utf-8")


if __name__ == "__main__":
    main()
